"""
Full pipeline test with real media: fragmented MP4 segments generated by ffmpeg are served by the
mock server, downloaded, merged to .ts, muxed by ffmpeg and moved to the output folder.
Skipped if ffmpeg/ffprobe are not installed.
"""
import glob
import json
import os
import shutil
import struct
import subprocess
import tempfile
import unittest

from tests.support import AUDIO_ITAG, VIDEO_ID, VIDEO_ITAG, FastTimings, MockServer, MockStream, make_info_dict
from tests.test_downloads import LOGGER, run_with_timeout

import download_Live
import getUrls

FFMPEG = shutil.which("ffmpeg")
FFPROBE = shutil.which("ffprobe")


def split_fragmented_mp4(path: str) -> tuple[bytes, list[bytes]]:
    """Split a fragmented MP4 into its init section (ftyp+moov) and moof+mdat fragments."""
    with open(path, "rb") as f:
        data = f.read()
    atoms = []
    ofs = 0
    while ofs + 8 <= len(data):
        size = struct.unpack(">I", data[ofs:ofs + 4])[0]
        atoms.append((data[ofs + 4:ofs + 8], data[ofs:ofs + size]))
        ofs += size
    init = b"".join(raw for name, raw in atoms if name in (b"ftyp", b"moov"))
    fragments, current = [], b""
    for name, raw in atoms:
        if name == b"moof" and current:
            fragments.append(current)
            current = b""
        if name not in (b"ftyp", b"moov", b"mfra"):
            current += raw
    if current:
        fragments.append(current)
    return init, fragments


@unittest.skipUnless(FFMPEG and FFPROBE, "ffmpeg/ffprobe not installed")
class FullPipelineTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.media = {}
        frag_flags = ["-movflags", "frag_keyframe+empty_moov+default_base_moof", "-frag_duration", "1000000"]
        video = os.path.join(self.tmp, "v.mp4")
        audio = os.path.join(self.tmp, "a.mp4")
        subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-f", "lavfi", "-i", "testsrc=duration=6:size=160x120:rate=10",
                        "-c:v", "libx264", "-g", "10", "-pix_fmt", "yuv420p", *frag_flags, video], check=True)
        subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-f", "lavfi", "-i", "sine=duration=6",
                        "-c:a", "aac", *frag_flags, audio], check=True)
        for itag, path in ((VIDEO_ITAG, video), (AUDIO_ITAG, audio)):
            init, fragments = split_fragmented_mp4(path)
            # Like YouTube, every segment repeats the init section (removed when merging)
            self.media[itag] = [init + frag for frag in fragments]
        self.total = min(len(self.media[VIDEO_ITAG]), len(self.media[AUDIO_ITAG]))

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_download_merge_and_move(self):
        stream = MockStream(total_segments=self.total, initial_head=self.total - 1, segment_duration=0.15,
                            nominal_duration=0.25, segment_provider=lambda itag, sq: self.media[itag][sq])
        out_dir = os.path.join(self.tmp, "output")
        temp_dir = os.path.join(self.tmp, "temp")
        original = getUrls.get_Video_Info
        with FastTimings(), MockServer(stream) as server:
            getUrls.get_Video_Info = lambda *a, **k: (make_info_dict(server, live_status="post_live"), "post_live")
            try:
                info = make_info_dict(server)
                options = {
                    "output": os.path.join(out_dir, "%(id)s"),
                    "temp_folder": temp_dir,
                    "threads": 2,
                    "segment_retries": 2,
                    "batch_size": 2,
                    "wait_limit": 0,
                    "merge": True,
                }
                coordinator = download_Live.LiveStreamDownloader(logger=LOGGER)
                coordinator.MIN_REFRESH_INTERVAL = coordinator.minimum_refresh_time = 0.0
                run_with_timeout(self, lambda: coordinator.download_segments(info, resolution="bv+ba/best", options=options), timeout=120)
            finally:
                getUrls.get_Video_Info = original

        final = os.path.join(out_dir, f"{VIDEO_ID}.mp4")
        self.assertTrue(os.path.exists(final), os.listdir(out_dir) if os.path.isdir(out_dir) else "no output dir")
        self.assertEqual(glob.glob(os.path.join(out_dir, "*.merging*")), [], "temporary merge file must be renamed")
        leftovers = [f for f in os.listdir(temp_dir) if f.endswith((".ts", ".temp", "-wal", "-shm"))]
        self.assertEqual(leftovers, [], "temporary stream files must be removed")
        probe = json.loads(subprocess.run([FFPROBE, "-v", "error", "-show_streams", "-show_format", "-of", "json", final],
                                          check=True, capture_output=True, text=True).stdout)
        kinds = sorted(s["codec_type"] for s in probe["streams"])
        self.assertEqual(kinds, ["audio", "video"])
        self.assertAlmostEqual(float(probe["format"]["duration"]), 6.0, delta=1.0)


if __name__ == "__main__":
    unittest.main()
